// Synthesises each voiceover line with Piper (open-source TTS), measures it,
// lays the lines out on a 45 s timeline and writes:
//   audio/voiceover.wav  - the mixed narration track
//   src/timeline.js      - beat and line timings the animation is driven by
//
// Usage: PIPER_VOICE=/path/to/en-us-lessac-medium.onnx node scripts/make-voiceover.js
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DURATION = 45;
const LEAD = [1.2, 0.5, 0.5, 0.5, 0.5]; // silence from beat start to line start
const MIN_TAIL = 0.7; // minimum silence after each line before the next beat
const FINAL_HOLD = 2.2; // "repeat" moment after the last line

const voice = process.env.PIPER_VOICE;
if (!voice || !fs.existsSync(voice)) {
  console.error('Set PIPER_VOICE to a Piper .onnx voice file (its .onnx.json must sit beside it).');
  process.exit(1);
}

const lines = JSON.parse(fs.readFileSync(path.join(ROOT, 'voiceover/lines.json'), 'utf8'));
const lineDir = path.join(ROOT, 'audio/lines');
fs.mkdirSync(lineDir, { recursive: true });

const probe = (file) =>
  Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).toString());

const durations = lines.map((line, i) => {
  const out = path.join(lineDir, `${i + 1}-${line.beat}.wav`);
  execFileSync('python3', ['-m', 'piper', '-m', voice, '-c', `${voice}.json`, '-f', out], { input: line.text });
  return probe(out);
});

// Spread any spare time evenly across the gaps after each line.
const natural = durations.reduce((sum, d, i) => sum + LEAD[i] + d + MIN_TAIL, 0) - MIN_TAIL + FINAL_HOLD;
const spare = DURATION - natural;
if (spare < 0) {
  console.error(`Narration needs ${natural.toFixed(2)} s but the video is ${DURATION} s. Shorten the lines.`);
  process.exit(1);
}
const pad = spare / lines.length;

let t = 0;
const beats = lines.map((line, i) => {
  const start = t;
  const voStart = start + LEAD[i];
  const voEnd = voStart + durations[i];
  const last = i === lines.length - 1;
  const end = last ? DURATION : voEnd + MIN_TAIL + pad;
  t = end;
  return { name: line.beat, start, end, voStart, voEnd, text: line.text };
});
const timeline = { duration: DURATION, fps: 60, repeatStart: beats[4].voEnd + 0.4, beats };

fs.writeFileSync(
  path.join(ROOT, 'src/timeline.js'),
  `// Generated by scripts/make-voiceover.js from the measured voiceover. Do not edit.\n` +
    `var TIMELINE = ${JSON.stringify(timeline, null, 2)};\n` +
    `if (typeof module !== 'undefined') module.exports = TIMELINE;\n`,
);

// Mix: delay each line to its start time, then pad/trim to exactly 45 s.
const inputs = lines.flatMap((line, i) => ['-i', path.join(lineDir, `${i + 1}-${line.beat}.wav`)]);
const delays = beats.map((b, i) => `[${i}]adelay=${Math.round(b.voStart * 1000)}:all=1[a${i}]`).join(';');
const mix = `${delays};${beats.map((_, i) => `[a${i}]`).join('')}amix=inputs=${beats.length}:normalize=0,apad,atrim=0:${DURATION}[out]`;
execFileSync('ffmpeg', ['-loglevel', 'error', '-y', ...inputs, '-filter_complex', mix, '-map', '[out]', '-ar', '48000', path.join(ROOT, 'audio/voiceover.wav')]);

for (const b of beats) {
  console.log(
    `${b.name.padEnd(13)} beat ${b.start.toFixed(2)}–${b.end.toFixed(2)} s   line ${b.voStart.toFixed(2)}–${b.voEnd.toFixed(2)} s`,
  );
}
console.log(`audio/voiceover.wav: ${probe(path.join(ROOT, 'audio/voiceover.wav')).toFixed(2)} s`);
